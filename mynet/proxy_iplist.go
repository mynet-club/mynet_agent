package mynet

// IP 段列表下发链路（chinaip / interip）。
//
// ctl 用 proxy:update-iplists 发布到 storage/app/public/proxy-lists/；
// 节点按 ProxyIPListRef.URL 拉取、校验 sha256/字节数，缓存到
// var/proxy-lists/<source>.txt，再由 L6 灌进 nft set / ipset。
//
// envelope **不内嵌**全量 CIDR（几 MB），只带 URL + 校验。

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/mynet-club/mynet_agent/shared"
	"github.com/mynet-club/mynet_agent/shared/domain"
	"github.com/mynet-club/mynet_agent/shared/utils"
)

// ProxyListCachePath 列表缓存路径。dir 通常为 var/proxy-lists。
func ProxyListCachePath(dir, source string) string {
	name := domain.ProxyListChina + ".txt"
	if source == domain.ProxyListInternational {
		name = domain.ProxyListInternational + ".txt"
	}
	return filepath.Join(dir, name)
}

// FetchProxyIPList 下载并校验列表，写入 cachePath。已缓存且校验通过则跳过下载。
//
// ref.URL 为空时不下载，仅接受已有缓存（离线/内网场景）。
// sha256 为空时跳过内容校验（过渡）；bytes>0 时校验长度。
func FetchProxyIPList(ref *domain.ProxyIPListRef, cachePath string, client *http.Client) (string, error) {
	if ref == nil {
		return "", fmt.Errorf("proxy ip_list 引用为空")
	}
	if client == nil {
		client = &http.Client{Timeout: 60 * time.Second}
	}
	if err := utils.SafeCreateDir(filepath.Dir(cachePath), 0o755); err != nil {
		return "", err
	}

	// 缓存命中（带校验）则直接用
	if data, err := os.ReadFile(cachePath); err == nil {
		if ipListDataOK(data, ref) {
			return cachePath, nil
		}
	}

	if ref.URL == "" {
		return "", fmt.Errorf("proxy 列表无 URL 且本地缓存无效: %s", cachePath)
	}

	resp, err := client.Get(ref.URL)
	if err != nil {
		return "", fmt.Errorf("下载 %s: %w", ref.URL, err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return "", fmt.Errorf("下载 %s: HTTP %d", ref.URL, resp.StatusCode)
	}
	data, err := io.ReadAll(io.LimitReader(resp.Body, 64<<20)) // 上限 64MB
	if err != nil {
		return "", fmt.Errorf("读 %s: %w", ref.URL, err)
	}
	if !ipListDataOK(data, ref) {
		return "", fmt.Errorf("列表校验失败: %s sha256=%s bytes=%d", ref.URL, shortHash(data), len(data))
	}
	// 先写临时再改名，避免半截文件
	tmp := cachePath + ".tmp"
	if err := os.WriteFile(tmp, data, 0o644); err != nil {
		return "", err
	}
	if err := os.Rename(tmp, cachePath); err != nil {
		return "", err
	}
	return cachePath, nil
}

func ipListDataOK(data []byte, ref *domain.ProxyIPListRef) bool {
	if ref.Bytes > 0 && int64(len(data)) != ref.Bytes {
		return false
	}
	if ref.SHA256 != "" {
		sum := sha256.Sum256(data)
		if !strings.EqualFold(hex.EncodeToString(sum[:]), ref.SHA256) {
			return false
		}
	}
	// 至少要像 CIDR 列表：有非空且含 '.' 或 '/' 的行
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if strings.Contains(line, ".") || strings.Contains(line, "/") {
			return true
		}
	}
	return false
}

func shortHash(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])[:12]
}

// CountIPListLines 有效 CIDR 行数（空行/注释不计）。
func CountIPListLines(data []byte) int {
	n := 0
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		n++
	}
	return n
}

// LoadIPSetFileCmds 把列表文件灌进 nft set / ipset（在 set 已创建之后）。
// nft：生成一次性 nft -f 片段路径由调用方准备；这里返回的是 ipset restore 兼容路径。
// 真正的大文件加载走 loadIPSetFromFile（写 nft 片段 / ipset restore），不走逐条 add。
func LoadIPSetFileCmds(snap *shared.SystemSnapshot, cachePath string) []routeCmd {
	if cachePath == "" {
		return nil
	}
	if snap.Capabilities["nft"] {
		// nft 片段文件路径固定，执行器保证先写好片段
		return []routeCmd{{
			argv: []string{"nft", "-f", cachePath + ".nft"},
		}}
	}
	if snap.Capabilities["iptables"] {
		return []routeCmd{{
			argv: []string{"ipset", "restore", "-exist"},
		}, {
			// stdin 由执行器喂 cachePath 转出的 restore 脚本
			argv: []string{"sh", "-c", "ipset restore -exist < " + cachePath + ".ipset"},
		}}
	}
	return nil
}

// WriteNftSetFragment 生成 nft -f 片段：flush set + add elements。
// 与旧线 route_policy.sh 的 nft set 格式对齐（flags interval）。
func WriteNftSetFragment(cachePath string) error {
	data, err := os.ReadFile(cachePath)
	if err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString("# generated by mynet proxy — do not edit\n")
	b.WriteString("add table ip mynet_proxy\n")
	b.WriteString("add set ip mynet_proxy dst4 { type ipv4_addr; flags interval; }\n")
	b.WriteString("flush set ip mynet_proxy dst4\n")
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fmt.Fprintf(&b, "add element ip mynet_proxy dst4 { %s }\n", line)
	}
	return os.WriteFile(cachePath+".nft", []byte(b.String()), 0o644)
}

// WriteIPSetRestore 生成 ipset restore 脚本。
func WriteIPSetRestore(cachePath string) error {
	data, err := os.ReadFile(cachePath)
	if err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString("# generated by mynet proxy\n")
	b.WriteString("create mynet_proxy hash:net -exist\n")
	b.WriteString("flush mynet_proxy\n")
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fmt.Fprintf(&b, "add mynet_proxy %s\n", line)
	}
	return os.WriteFile(cachePath+".ipset", []byte(b.String()), 0o644)
}

// proxyIPListRef 从策略里取 IP 列表引用。
func proxyIPListRef(p *domain.ProxyPolicy) *domain.ProxyIPListRef {
	if p == nil || p.Split == nil {
		return nil
	}
	return p.Split.IPList
}
