package mynet

// 域名规则落地：网关 → dnsmasq 片段；PC → 上游指针（不装 dnsmasq）。
// 见 spec/proxy-split.md §3.4。

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/mynet-club/mynet_agent-V2/shared/domain"
)

// DNSForm 形态。
const (
	DNSFormGateway = "gateway" // 本地 dnsmasq/SmartDNS
	DNSFormPC      = "pc"      // 只配 nameserver / DoH
)

// DomainDNSPlan 由规则算出的落地计划。
type DomainDNSPlan struct {
	Form string
	// Gateway：dnsmasq 配置路径与 reload 命令
	ConfPath   string
	ReloadCmds [][]string
	// PC：直接写入的上游
	Nameservers []string
	DoH         string
}

// PlanDomainDNS 按形态生成计划。
func PlanDomainDNS(rules *domain.ProxyDomainRules, form string, confPath string) DomainDNSPlan {
	if rules == nil {
		rules = &domain.ProxyDomainRules{}
	}
	if form == DNSFormPC {
		return DomainDNSPlan{
			Form:        DNSFormPC,
			Nameservers: []string{rules.EffectivePlatformDNS()},
			DoH:         "",
		}
	}
	// 网关：默认 dnsmasq 片段路径
	if confPath == "" {
		confPath = "/tmp/mynet-dns-split.conf"
	}
	return DomainDNSPlan{
		Form:        DNSFormGateway,
		ConfPath:    confPath,
		ReloadCmds:  DNSSplitReloadCmds(""),
		Nameservers: rules.EffectiveDirectDNS(),
	}
}

// WriteDomainDNSSplitConf 网关形态：生成 dnsmasq 分流片段。
//
//	server=223.5.5.5
//	server=/google.com/8.8.8.8          ← clean 列表
//	server=/github.com/dns.mynet.club   ← proxied + fast → 平台 DNS
//	server=/baidu.com/223.5.5.5         ← direct
func WriteDomainDNSSplitConf(rules *domain.ProxyDomainRules, path string) error {
	if rules == nil {
		rules = &domain.ProxyDomainRules{}
	}
	var b strings.Builder
	b.WriteString("# generated by mynet proxy domain-dns — do not edit\n")
	b.WriteString("# form=gateway  见 spec/proxy-split.md §3.4\n")

	// 默认上游 = 国内（快）
	for _, d := range rules.EffectiveDirectDNS() {
		d = strings.TrimSpace(d)
		if d != "" {
			b.WriteString("server=" + d + "\n")
		}
	}

	// 并集所有点名域名，逐个写 server=
	names := map[string]upstreamSlot{}
	add := func(domains []string, resolve func(string) []string) {
		for _, raw := range domains {
			d := normalizeDomainName(raw)
			if d == "" {
				continue
			}
			if _, ok := names[d]; ok {
				continue
			}
			names[d] = upstreamSlot{ups: resolve(d)}
		}
	}
	add(rules.Direct, func(d string) []string {
		u, _ := rules.ResolveDNSSplit(d)
		return u
	})
	add(rules.Proxied, func(d string) []string {
		u, _ := rules.ResolveDNSSplit(d)
		return u
	})
	add(rules.UpstreamClean, func(d string) []string {
		u, _ := rules.ResolveDNSSplit(d)
		return u
	})

	keys := make([]string, 0, len(names))
	for k := range names {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		for _, up := range names[k].ups {
			up = strings.TrimSpace(up)
			if up == "" {
				continue
			}
			fmt.Fprintf(&b, "server=/%s/%s\n", k, up)
		}
	}

	// T14：proxied 域名解析出的 A 记录 → ipset mynet_proxy（增量，dnsmasq 原生）
	// 只对「会走代理」的域名挂 ipset；direct 不进集合。
	var proxiedForIPSet []string
	proxiedForIPSet = append(proxiedForIPSet, rules.Proxied...)
	proxiedForIPSet = append(proxiedForIPSet, rules.UpstreamClean...)
	for _, line := range DnsmasqIPSetLines(proxiedForIPSet, "mynet_proxy") {
		b.WriteString(line + "\n")
	}

	fmt.Fprintf(&b, "# platform dns: %s\n", rules.EffectivePlatformDNS())

	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

type upstreamSlot struct {
	ups []string
}

func normalizeDomainName(d string) string {
	d = strings.TrimSpace(strings.ToLower(d))
	d = strings.TrimPrefix(d, "*.")
	d = strings.TrimPrefix(d, ".")
	return d
}

// PCNameserverResolv PC 形态写 resolv.conf（只指平台/公共 DNS）。
func PCNameserverResolv(rules *domain.ProxyDomainRules, resolvPath string) (old string, err error) {
	if rules == nil {
		rules = &domain.ProxyDomainRules{}
	}
	ns := rules.EffectivePlatformDNS()
	return WriteResolvConf(resolvPath, ns)
}

// ApplyProxyDNSFiles 按形态写 DNS 产物（P0-b）。
// 网关：dnsmasq 片段（含 ipset=）；PC：resolv 指平台 DNS。
// 返回需要执行的 reload 命令。
func ApplyProxyDNSFiles(p *domain.ProxyPolicy, form string, confPath, resolvPath string) ([][]string, error) {
	if p == nil || !p.Enabled {
		return nil, nil
	}
	rules := p.DomainRules
	if rules == nil {
		rules = &domain.ProxyDomainRules{}
	}
	switch form {
	case DNSFormPC:
		if resolvPath == "" {
			resolvPath = "/etc/resolv.conf"
		}
		if _, err := PCNameserverResolv(rules, resolvPath); err != nil {
			return nil, err
		}
		return nil, nil
	default:
		if confPath == "" {
			confPath = "/tmp/mynet-dns-split.conf"
		}
		if err := WriteDomainDNSSplitConf(rules, confPath); err != nil {
			return nil, err
		}
		return DNSSplitReloadCmds(""), nil
	}
}

// DynamicIPSetFilePath 动态 IP 暂存（DNS 回答钩子写入，apply 读出增量入集）。
func DynamicIPSetFilePath(base string) string {
	if base == "" {
		base = "var/proxy"
	}
	return filepath.Join(base, "dynamic-ipset.json")
}

// LoadDynamicIPSetFile 读 { "ips": ["1.2.3.4"] }。
func LoadDynamicIPSetFile(path string) ([]string, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, err
	}
	var body struct {
		IPs []string `json:"ips"`
	}
	if err := json.Unmarshal(raw, &body); err != nil {
		return nil, err
	}
	return body.IPs, nil
}

// SaveDynamicIPSetFile 写入动态 IP 列表（供 DNS 回答钩子 / 测试）。
func SaveDynamicIPSetFile(path string, ips []string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	raw, _ := json.Marshal(map[string]any{"ips": ips})
	return os.WriteFile(path, raw, 0o644)
}
