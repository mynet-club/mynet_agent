package mynet

// DNS 策略落地（旧线 DNS_MODE：none / redirect / resolv / split）。
//
// redirect/resolv 的命令生成在 proxy_apply.go 的 proxyDNSCmds；
// 本文件负责**文件写入类**操作：resolv.conf、dnsmasq split 配置。
//
// split 的域名列表来源（gfwlist + 额外国外域名）由调用方准备成两个文件，
// 这里只负责拼 dnsmasq `server=/domain/上游` 并 reload（不 restart）。

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// ForeignDNSServers 兜底公共 DNS（与 proxy_apply.DefaultForeignDNSServers 同源）。
// split 模式的 dnsmasq `server=dns.mynet.club` 是最后一道兜底，不在此列表。

// WriteResolvConf 写 /etc/resolv.conf（或调用方给的 path）。
// 返回旧内容，便于 stop 时恢复。
func WriteResolvConf(path, nameserver string) (old string, err error) {
	if nameserver == "" {
		return "", fmt.Errorf("resolv nameserver 为空")
	}
	if path == "" {
		path = "/etc/resolv.conf"
	}
	oldBytes, _ := os.ReadFile(path)
	body := "# generated by mynet proxy — do not edit\nnameserver " + nameserver + "\n"
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		return string(oldBytes), err
	}
	return string(oldBytes), nil
}

// RestoreResolvConf 用旧内容恢复；old 为空则写回默认（仅注释头）。
func RestoreResolvConf(path, old string) error {
	if path == "" {
		path = "/etc/resolv.conf"
	}
	if old == "" {
		old = "# restored by mynet proxy\n"
	}
	return os.WriteFile(path, []byte(old), 0o644)
}

// DNSSplitOptions split 模式参数。
type DNSSplitOptions struct {
	// DomesticServers 国内上游（dnsmasq 默认 server=）。
	DomesticServers []string
	// ForeignServer 国外域名上游。
	ForeignServer string
	// DomainFiles 域名列表文件（gfwlist + 额外），每行一个域名；# 注释。
	DomainFiles []string
	// ConfPath 输出的 dnsmasq 配置片段路径。
	ConfPath string
	// FallbackDomain 兜底域名（dns.mynet.club），可空。
	FallbackDomain string
}

// WriteDNSSplitConf 生成 dnsmasq 分流片段。
//
// 格式（spec/proxy.md）：
//
//	server=223.5.5.5
//	server=/google.com/8.8.8.8
//	server=dns.mynet.club     ← 仅 fallback
func WriteDNSSplitConf(opt DNSSplitOptions) error {
	if opt.ForeignServer == "" {
		return fmt.Errorf("split 缺 foreign server")
	}
	if opt.ConfPath == "" {
		return fmt.Errorf("split 缺 conf path")
	}
	var b strings.Builder
	b.WriteString("# generated by mynet proxy dns-split — do not edit\n")
	for _, d := range opt.DomesticServers {
		d = strings.TrimSpace(d)
		if d != "" {
			b.WriteString("server=" + d + "\n")
		}
	}
	seen := map[string]bool{}
	for _, f := range opt.DomainFiles {
		data, err := os.ReadFile(f)
		if err != nil {
			return fmt.Errorf("读域名列表 %s: %w", f, err)
		}
		for _, line := range strings.Split(string(data), "\n") {
			line = strings.TrimSpace(line)
			if line == "" || strings.HasPrefix(line, "#") {
				continue
			}
			line = strings.TrimPrefix(line, ".")
			if seen[line] {
				continue
			}
			seen[line] = true
			b.WriteString("server=/" + line + "/" + opt.ForeignServer + "\n")
		}
	}
	if opt.FallbackDomain != "" {
		b.WriteString("server=" + opt.FallbackDomain + "\n")
	}
	if err := os.MkdirAll(filepath.Dir(opt.ConfPath), 0o755); err != nil {
		return err
	}
	return os.WriteFile(opt.ConfPath, []byte(b.String()), 0o644)
}

// DNSSplitReloadCmds reload（不是 restart，避免中断 in-flight 查询）。
//
// ⚠️ 不按名字杀进程（安全红线）：用 pidfile 精确 HUP，或系统服务管理器。
// 优先级：systemctl reload → service dnsmasq reload → pidfile HUP。
func DNSSplitReloadCmds(dnsmasqPidFile string) [][]string {
	cmds := [][]string{
		{"dnsmasq", "--test"},
		{"systemctl", "reload", "dnsmasq"},
	}
	if dnsmasqPidFile != "" {
		// pidfile + kill -HUP，精确到实例
		cmds = append(cmds, []string{
			"sh", "-c", "kill -HUP \"$(cat " + dnsmasqPidFile + ")\"",
		})
	}
	return cmds
}
