package mynet

// proxy 插件 → 驱动投影（gnb p2-route-proxy）。
//
// ⚠️ 语义：出口对端是**数据路径的目标**，不是 mesh 的 f/forward 中转。
// gnb address.conf 里该对端的角色码写 `f`（驱动协议事实），
// 产品含义是「proxy egress（出口）」，不是「forward 节点」。
//
// 用户在插件里决定：开不开、从哪些 peer 出去、权重/顺序。
// apply 时：
//   1. 探测当前 gnb 是否支持 proxy（P2 补丁）
//   2. 不支持 → 高声提醒，不写 proxy.conf，不把 intent 打成 proxy on
//   3. 支持  → 写 driver/gnb/conf/<id>/proxy.conf，
//              并把出口对端写入 address.conf（角色码 f，gnb 协议事实；产品上=出口目标）
//
// GNB（p2-route-proxy）认 node.conf 的 `proxy on` + 出口对端；
// proxy.conf 是插件意图在驱动目录的投影（选点/权重/顺序），供人读、供排障、
// 将来 gnb 若扩展 peer 选择也能直接吃。

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/mynet-club/mynet_agent-V2/mynet/driver"
	"github.com/mynet-club/mynet_agent-V2/shared/config"
	"github.com/mynet-club/mynet_agent-V2/shared/domain"
	"github.com/mynet-club/mynet_agent-V2/shared/utils"
)

// GNBProxySupported 探测函数可注入（测试/不同探测策略）。
// 默认：找 gnb 二进制，判 P2（proxy）能力。
var GNBProxySupported = probeGNBProxySupport

// probeGNBProxySupport 当前 gnb 是否带 P2（proxy）能力。
//
// 判据（对齐 p2-route-proxy 0005-show-features-line.patch）：
// 跑 `gnb -h` / `gnb --help`，看是否输出机器可读的
//
//	Features: proxy
//
// 未打 P2 的 gnb 没有这行 —— 与行为一致，不扫二进制。
// 找不到 gnb 时**不假装支持**。
func probeGNBProxySupport() (bool, string) {
	bin := findGnbBin()
	if bin == "" {
		return false, "找不到 gnb 二进制"
	}
	// show_description() 在 -h/--help 路径输出 Features
	for _, args := range [][]string{{"-h"}, {"--help"}, {}} {
		out, err := exec.Command(bin, args...).CombinedOutput()
		if err != nil && len(out) == 0 {
			continue
		}
		text := string(out)
		for _, line := range strings.Split(text, "\n") {
			line = strings.TrimSpace(line)
			if !strings.HasPrefix(line, "Features:") {
				continue
			}
			for _, f := range strings.Fields(strings.TrimPrefix(line, "Features:")) {
				if f == "proxy" {
					return true, "gnb Features: proxy（P2）"
				}
			}
			return false, "当前 gnb Features 无 proxy（未打 P2 补丁）"
		}
	}
	return false, "当前 gnb 无 Features 行（未打 P2 补丁或版本过旧；需 0005-show-features-line）"
}

func findGnbBin() string {
	// 与 driver.resolveGNBBinary 同一优先级：MYNET_HOME/driver/gnb/bin 优先，
	// 不要一上来就 LookPath —— 系统 PATH 里可能是旧 gnb。
	name := utils.ExeName("gnb")
	home := utils.GetMyNetHome()
	candidates := []string{
		filepath.Join(home, "driver", "gnb", "bin", name),
		filepath.Join(home, "driver", "gnb", "bin", "gnb"),
		"/usr/local/opt/mynet/driver/gnb/bin/gnb",
		"/usr/local/bin/gnb",
		"/usr/bin/gnb",
	}
	for _, c := range candidates {
		if st, err := os.Stat(c); err == nil && !st.IsDir() {
			return c
		}
	}
	if p, err := exec.LookPath(name); err == nil {
		return p
	}
	return ""
}

// RenderGnbProxyConf 插件意图 → driver 目录下的 proxy.conf。
func RenderGnbProxyConf(c *domain.PluginProxyConfig) string {
	var b strings.Builder
	b.WriteString("# generated by mynet plugin proxy — do not edit\n")
	b.WriteString("# 本文件是 proxy 插件意图在 gnb 目录的投影（选点/权重/顺序）。\n")
	b.WriteString("# gnb v3: group 是目的地区域策略；role 是 client/server/both。\n")
	role := c.Role
	if role == "" {
		role = "client"
	}
	fmt.Fprintf(&b, "role %s\n", role)
	b.WriteString("proxy on\n")
	if role == "server" || role == "both" {
		b.WriteString("ingress_open on\n")
	}
	if c.Outbound.Mode != "" {
		fmt.Fprintf(&b, "mode %s\n", c.Outbound.Mode)
	}
	if c.Outbound.Via != "" {
		fmt.Fprintf(&b, "via %s\n", c.Outbound.Via)
	}
	if c.MaxExits > 0 {
		fmt.Fprintf(&b, "max_exits %d\n", c.MaxExits)
	}
	for i, e := range c.EffectiveExits() {
		order := e.Order
		if order == 0 {
			order = i + 1
		}
		w := e.Weight
		if w <= 0 {
			w = 10
		}
		fmt.Fprintf(&b, "exit %d|%s|%d\n", order, e.NodeID, w)
	}
	return b.String()
}

// ApplyProxyToGnb 把 proxy 插件意图落到 gnb 投影目录。
// 返回是否真正写入；unsupported 时只告警不写。
func ApplyProxyToGnb(confDir string, c *domain.PluginProxyConfig, dry bool) (written bool, warn string, err error) {
	ok, reason := GNBProxySupported()
	if !ok {
		// 不支持：明确提醒，不写半截配置（写了 gnb 也不认，反而误导）
		return false, fmt.Sprintf("⚠ 当前系统 gnb 不支持 proxy：%s —— 跳过 proxy.conf（请升级带 P2 补丁的 gnb）", reason), nil
	}
	body := RenderGnbProxyConf(c)
	if dry {
		fmt.Printf("dry-run: 将写入 %s/proxy.conf（%d 个出口）\n", confDir, len(c.EffectiveExits()))
		return false, reason, nil
	}
	if err := utils.SafeCreateDir(confDir, 0o700); err != nil {
		return false, "", err
	}
	if err := os.WriteFile(filepath.Join(confDir, "proxy.conf"), []byte(body), 0o644); err != nil {
		return false, "", err
	}
	return true, reason, nil
}

// applyProxyForwarding 设置 gnb proxy 意图（proxy on）。
//
// **不写 address.conf 角色、不进 ForwardNodes**：
// 出口对端是数据路径的目标，等同把目的网段以该节点为下一跳写入 route.conf。
func applyProxyForwarding(g *domain.GnbIntent, exits []domain.ProxyExit) {
	if g == nil || len(exits) == 0 {
		return
	}
	// 出口对端 = 数据路径的目标，**不写 address.conf 的 f 角色**，
	// 不进 ForwardNodes。数据路径由 node.conf `proxy on` + 出口对端决定（对端即下一跳）。
	if g.Forwarding == nil {
		g.Forwarding = &domain.GnbForwarding{}
	}
	g.Forwarding.Proxy = true
	g.Forwarding.Direct = true
}

// enrichIntentWithProxy 若 proxy 插件启用 **且 gnb 支持**，把出口写进 GnbIntent。
// 不支持时不动 intent（不写 proxy on），只把警告留给 writeProxyProjection。
func enrichIntentWithProxy(g *domain.GnbIntent) *domain.PluginProxyConfig {
	store := &config.Store{}
	src, _, err := store.ActiveSource()
	if err != nil {
		return nil
	}
	pdir := utils.PluginsConfDir(src)
	cfg, err := store.LoadPlugin(pdir, domain.PluginNameProxy)
	if err != nil || !cfg.Enabled {
		return nil
	}
	pp, err := domain.DecodePluginProxy(cfg)
	if err != nil {
		return nil
	}
	if ok, _ := GNBProxySupported(); !ok {
		// 能力不足：不碰 intent，避免 node.conf 出现无效的 proxy on
		return pp
	}
	applyProxyForwarding(g, pp.EffectiveExits())
	return pp
}

// writeProxyProjection 在 gnb 投影写完后补 proxy.conf。
func writeProxyProjection(nodeID string, pp *domain.PluginProxyConfig, dry bool) error {
	if pp == nil {
		return nil
	}
	dir := filepath.Join(utils.GnbConfDir(), nodeID)
	written, warn, err := ApplyProxyToGnb(dir, pp, dry)
	if err != nil {
		return err
	}
	if warn != "" {
		fmt.Println(warn)
	}
	if written {
		fmt.Printf("✓ proxy.conf（%d 出口）\n", len(pp.EffectiveExits()))
	}
	return nil
}

