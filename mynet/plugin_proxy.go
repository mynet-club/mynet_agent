// GNBProxySupported 探测函数可注入（测试/不同探测策略）。
// 默认：找 gnb 二进制，判 P2（proxy）能力。
var GNBProxySupported = probeGNBProxySupport

// probeGNBProxySupport 当前 gnb 是否带 P2（proxy）能力。
//
// 主判据：`gnb -h/-v/无参` 输出机器可读的 `Features: proxy` 行
// （p2-route-proxy 补丁序列的 0005-show-features-line 提供）。
// 现网 2026-09-30 之前出厂的 gnb 没编入 0005，只认 Features 行会把它们
// 误判成没打 P2。兜底判据对齐出厂契约 MANIFEST 的 mark_p2：
// 二进制里含 proxy.conf 行为字符串（如 "proxy.conf loaded"）即认 P2。
// Features 行若存在但不含 proxy，是明确否定，不走兜底。
// 找不到 gnb 时**不假装支持**。
func probeGNBProxySupport() (bool, string) {
	bin := findGnbBin()
	if bin == "" {
		return false, "找不到 gnb 二进制"
	}
	// show_description() 在 -h/--help 路径输出 Features
	for _, args := range [][]string{{"-h"}, {"--help"}, {}} {
		out, err := exec.Command(bin, args...).CombinedOutput()
		if err != nil && len(out) == 0 {
			continue
		}
		text := string(out)
		for _, line := range strings.Split(text, "\n") {
			line = strings.TrimSpace(line)
			if !strings.HasPrefix(line, "Features:") {
				continue
			}
			for _, f := range strings.Fields(strings.TrimPrefix(line, "Features:")) {
				if f == "proxy" {
					return true, "gnb Features: proxy（P2）"
				}
			}
			return false, "当前 gnb Features 无 proxy（未打 P2 补丁）"
		}
	}
	if gnbHasP2Marker(bin) {
		return true, "gnb 含 p2 proxy.conf 行为字符串（兜底探测，对齐出厂 MANIFEST mark_p2）"
	}
	return false, "当前 gnb 无 P2（proxy）能力：既无 Features 行，也无 proxy.conf 行为字符串"
}

// gnbHasP2Marker 扫二进制找 p2-route-proxy 的行为字符串。
// 取值与 mynet_gnb 出厂 MANIFEST 的 mark_p2 一致（0001-proxy-conf-v3 必然带入）。
func gnbHasP2Marker(bin string) bool {
	data, err := os.ReadFile(bin)
	if err != nil {
		return false
	}
	return strings.Contains(string(data), "proxy.conf loaded")
}

// provisionProxyPlugin 出厂补丁栈判定支持 p2 时，把 proxy 插件包落到
// $MYNET_HOME/plugins/proxy/manifest.json —— 纯配置壳（Entry 从不执行），
// 让 WebUI/CLI 显示「已安装」；是否启用留给用户，这里不写插件配置。
// 已存在则不动（幂等）。与 utils.PluginPackageDir 同一目录布局。
func provisionProxyPlugin(home string) (bool, error) {
	dir := filepath.Join(home, "plugins", domain.PluginNameProxy)
	mf := filepath.Join(dir, "manifest.json")
	if _, err := os.Stat(mf); err == nil {
		return false, nil
	}
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return false, err
	}
	m := PluginPackage{
		Name:    domain.PluginNameProxy,
		Version: utils.GnbBaseline,
		Entry:   "bin/" + domain.PluginNameProxy,
		Desc:    "gnb p2-route-proxy 配置壳（出厂补丁栈带入）",
	}
	if err := writeJSON(mf, m, 0o644); err != nil {
		return false, err
	}
	return true, nil
}

func findGnbBin() string {
	// 与 driver.resolveGNBBinary 同一优先级：MYNET_HOME/driver/gnb/bin 优先，
	// 不要一上来就 LookPath —— 系统 PATH 里可能是旧 gnb。
	name := utils.ExeName("gnb")
	home := utils.GetMyNetHome()
	candidates := []string{
		filepath.Join(home, "driver", "gnb", "bin", name),
		filepath.Join(home, "driver", "gnb", "bin", "gnb"),
		"/usr/local/opt/mynet/driver/gnb/bin/gnb",
		"/opt/mynet/driver/gnb/bin/gnb", // pkg 落地位，与 driver.resolveGNBBinary 同序
		"/usr/local/bin/gnb",
		"/usr/bin/gnb",
	}
	for _, c := range candidates {
		if st, err := os.Stat(c); err == nil && !st.IsDir() {
			return c
		}
	}
	if p, err := exec.LookPath(name); err == nil {
		return p
	}
	return ""
}

// RenderGnbProxyConf 插件意图 → driver/gnb/conf/<id>/proxy.conf。
//
// 输出必须是 **P2 gnb 认的格式**（p2-route-proxy README / TEST-REPORT §2）：
//
//	role client|server|both     必填
//	proxy on|off
//	ingress_open on|off         仅 server/both；client 默认 off 不写
//
//	[default]                   兜底出口
//	exit <uuid> w=N [order=N]
//
//	[group <name>]              按目的分流
//	target <cidr>
//	exit <uuid> w=N [order=N]
//
// ⚠️ 不要写 mode/via/max_exits，也不要写 `exit 1|uuid|w` 管道格式 —— P2 不认。
// order=0 是合法最低层，不要改写成 1-based。
func RenderGnbProxyConf(c *domain.PluginProxyConfig) string {
	var b strings.Builder
	b.WriteString("# generated by mynet plugin proxy — do not edit\n")
	b.WriteString("# gnb p2-route-proxy proxy.conf 投影（出口选点/权重/顺序/分组）\n")
	role := c.Role
	if role == "" {
		role = "client"
	}
	fmt.Fprintf(&b, "role %s\n", role)
	b.WriteString("proxy on\n")
	if role == "server" || role == "both" {
		b.WriteString("ingress_open on\n")
	}

	// [default] —— 未命中任何 group 时的兜底
	exits := c.EffectiveExits()
	if len(exits) > 0 {
		b.WriteString("\n[default]\n")
		writeProxyExits(&b, exits)
	}

	// [group name] —— 目的地区域分流
	for _, g := range c.Groups {
		if g.Name == "" {
			continue
		}
		fmt.Fprintf(&b, "\n[group %s]\n", g.Name)
		for _, t := range g.Targets {
			t = strings.TrimSpace(t)
			if t == "" {
				continue
			}
			// P2 拒载 /0；这里直接跳过，避免整文件被拒
			if t == "0.0.0.0/0" || t == "0/0" {
				continue
			}
			fmt.Fprintf(&b, "target %s\n", t)
		}
		var gx []domain.ProxyExit
		for _, e := range g.Exits {
			if e.Enabled && e.NodeID != "" {
				gx = append(gx, e)
			}
		}
		sort.SliceStable(gx, func(i, j int) bool {
			if gx[i].Order != gx[j].Order {
				if gx[i].Order == 0 {
					return false
				}
				if gx[j].Order == 0 {
					return true
				}
				return gx[i].Order < gx[j].Order
			}
			return gx[i].Weight > gx[j].Weight
		})
		if len(gx) > 0 {
			writeProxyExits(&b, gx)
		}
		// 组内无出口 = DROP（P2 语义），不回落 default —— 不补任何东西
	}
	return b.String()
}

// writeProxyExits 写 `exit <uuid> w=N [order=N]` 行。
func writeProxyExits(b *strings.Builder, exits []domain.ProxyExit) {
	for _, e := range exits {
		w := e.Weight
		if w <= 0 {
			w = 10
		}
		// order=0 合法（最低层），只有显式 >0 才写
		if e.Order > 0 {
			fmt.Fprintf(b, "exit %s w=%d order=%d\n", e.NodeID, w, e.Order)
		} else {
			fmt.Fprintf(b, "exit %s w=%d\n", e.NodeID, w)
		}
	}
}

// ApplyProxyToGnb 把 proxy 插件意图落到 gnb 投影目录。
// 返回是否真正写入；unsupported 时只告警不写。
func ApplyProxyToGnb(confDir string, c *domain.PluginProxyConfig, dry bool) (written bool, warn string, err error) {
	ok, reason := GNBProxySupported()
	if !ok {
		// 不支持：明确提醒，不写半截配置（写了 gnb 也不认，反而误导）
		return false, fmt.Sprintf("⚠ 当前系统 gnb 不支持 proxy：%s —— 跳过 proxy.conf（请升级带 P2 补丁的 gnb）", reason), nil
	}
	body := RenderGnbProxyConf(c)
	if dry {
		fmt.Printf("dry-run: 将写入 %s/proxy.conf（%d 个出口）\n", confDir, len(c.EffectiveExits()))
		return false, reason, nil
	}
	if err := utils.SafeCreateDir(confDir, 0o700); err != nil {
		return false, "", err
	}
	if err := os.WriteFile(filepath.Join(confDir, "proxy.conf"), []byte(body), 0o644); err != nil {
		return false, "", err
	}
	return true, reason, nil
}

// applyProxyForwarding 确保 gnb 出口节点开启直连转发（direct-forwarding）。
//
// proxy 的开关与出口数据路径全部由独立 proxy.conf 承载；node.conf 不再写
// `proxy on`。出口对端是数据路径的目标，**不写 address.conf 的 f 角色**、
// 不进 ForwardNodes。
func applyProxyForwarding(g *domain.GnbIntent, exits []domain.ProxyExit) {
	if g == nil || len(exits) == 0 {
		return
	}
	if g.Forwarding == nil {
		g.Forwarding = &domain.GnbForwarding{}
	}
	g.Forwarding.Direct = true
}

// enrichIntentWithProxy 若 proxy 插件启用 **且 gnb 支持**，把出口写进 GnbIntent
// （只动 direct-forwarding；proxy 开关归独立 proxy.conf）。
// 不支持时不动 intent，只把警告留给 writeProxyProjection。
func enrichIntentWithProxy(g *domain.GnbIntent) *domain.PluginProxyConfig {
	store := &config.Store{}
	src, _, err := store.ActiveSource()
	if err != nil {
		return nil
	}
	pdir := utils.PluginsConfDir(src)
	cfg, err := store.LoadPlugin(pdir, domain.PluginNameProxy)
	if err != nil || !cfg.Enabled {
		return nil
	}
	pp, err := domain.DecodePluginProxy(cfg)
	if err != nil {
		return nil
	}
	if ok, _ := GNBProxySupported(); !ok {
		// 能力不足：不碰 intent
		return pp
	}
	applyProxyForwarding(g, pp.EffectiveExits())
	return pp
}

// writeProxyProjection 在 gnb 投影写完后补 proxy.conf。
func writeProxyProjection(nodeID string, pp *domain.PluginProxyConfig, dry bool) error {
	if pp == nil {
		return nil
	}
	dir := filepath.Join(utils.GnbConfDir(), nodeID)
	written, warn, err := ApplyProxyToGnb(dir, pp, dry)
	if err != nil {
		return err
	}
	if warn != "" {
		fmt.Println(warn)
	}
	if written {
		fmt.Printf("✓ proxy.conf（%d 出口）\n", len(pp.EffectiveExits()))
	}
	return nil
}

